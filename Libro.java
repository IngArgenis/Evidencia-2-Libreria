public class Libro {
    // Los tres atributos solicitados
    String titulo;
    String autor;
    int anioPublicacion;

    // Constructor para guardar los datos más rápido al crear el libro
    public Libro(String tit, String aut, int anio) {
        titulo = tit;
        autor = aut;
        anioPublicacion = anio;
    }
}